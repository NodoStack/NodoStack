document.getElementById("idioma-btn").addEventListener("click", () => {
  const lang = document.documentElement.lang === "es" ? "en" : "es";
  document.documentElement.lang = lang;
  const t = traducciones[lang];

  // Navbar
  const navLinks = document.querySelectorAll(".navbar-nav .nav-link");
  const navKeys = ["sobre", "servicios", "proyectos", "equipo", "contacto"];
  navLinks.forEach((link, i) => link.textContent = t.navbar[navKeys[i]]);

  // Hero
  document.querySelector(".slogan").textContent = t.hero.slogan;

  // ¿Qué resolvemos?
  document.querySelector("section.bg-accento h2").textContent = t.resolvemos.titulo;
  const resolvemosItems = document.querySelectorAll("section.bg-accento h5");
  const resolvemosTextos = document.querySelectorAll("section.bg-accento p");
  resolvemosItems.forEach((el, i) => el.textContent = t.resolvemos.items[i]);
  resolvemosTextos.forEach((el, i) => el.textContent = t.resolvemos.textos[i]);

  //sobre nosotras
  // Sobre nosotras
const sobreTitulo = document.querySelector("#sobre-nosotras h2");
const sobreTexto = document.querySelector("#sobre-nosotras p");
if (sobreTitulo) sobreTitulo.textContent = t.sobreNosotras.titulo;
if (sobreTexto) sobreTexto.textContent = t.sobreNosotras.descripcion;

// Botón "Consulta gratis"
const consultaBtn = document.getElementById("consulta-btn");
if (consultaBtn) consultaBtn.textContent = t.consultaGratis;

  // Servicios
  document.querySelector("#stack h2").textContent = t.servicios.titulo;
  const serviciosItems = document.querySelectorAll("#stack h5");
  const serviciosTextos = document.querySelectorAll("#stack p.text-muted");
  serviciosItems.forEach((el, i) => el.textContent = t.servicios.items[i].titulo);
  serviciosTextos.forEach((el, i) => el.textContent = t.servicios.items[i].texto);

  // Soluciones
  document.querySelector("#soluciones h2").textContent = t.soluciones.titulo;
  document.querySelector("#soluciones p.lead").textContent = t.soluciones.descripcion;
  const cards = document.querySelectorAll("#soluciones .card-body");
  cards.forEach((card, i) => {
    card.querySelector("h4").textContent = t.soluciones.proyectos[i].titulo;
    card.querySelector("p").textContent = t.soluciones.proyectos[i].texto;
    const items = card.querySelectorAll("ul li");
    items.forEach((li, j) => {
      li.textContent = t.soluciones.proyectos[i].items[j];
    });
  });

  // Equipo
  document.querySelector("#equipo h2").textContent = t.equipo.titulo;
  const roles = document.querySelectorAll("#equipo .card-text");
  roles.forEach(el => el.textContent = t.equipo.rol);

  // Contacto
  document.querySelector("#contacto h2").textContent = t.contacto.titulo;
  document.querySelector("#contacto p").textContent = t.contacto.descripcion;
  const labels = document.querySelectorAll("#contacto label");
  labels[0].textContent = t.contacto.form.nombre;
  labels[1].textContent = t.contacto.form.email;
  labels[2].textContent = t.contacto.form.mensaje;

  document.querySelector("input[name='nombre']").placeholder = t.contacto.form.placeholderNombre;
  document.querySelector("input[name='_replyto']").placeholder = t.contacto.form.placeholderEmail;
  document.querySelector("textarea[name='mensaje']").placeholder = t.contacto.form.placeholderMensaje;
  document.querySelector("button[type='submit']").textContent = t.contacto.form.boton;

  // WhatsApp
  const whatsappText = document.querySelector("#contacto .text-center.mt-4 p");
  const whatsappBtn = document.querySelector("#contacto .btn-outline-light");
  if (whatsappText) whatsappText.textContent = t.contacto.whatsapp;
  if (whatsappBtn) whatsappBtn.textContent = t.contacto.botonWhatsapp;

  // Footer
  document.querySelector("footer p").textContent = t.footer;

  // Botón de idioma
  document.getElementById("idioma-btn").textContent = t.idiomaBtn;
});
